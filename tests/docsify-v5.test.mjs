test('links section landing pages by their route, not README.md', async () => {
  // `README.md` resolves to #/<section>/README, while the menu and home page
  // link to #/<section>/. Docsify only marks the sidebar item active (and
  // pagination only finds the page) when the two match.
  const { readdir } = await import('node:fs/promises');
  const root = new URL('../', import.meta.url);
  const entries = await readdir(root, { withFileTypes: true });
  for (const entry of entries.filter(e => e.isDirectory())) {
    const sidebar = await readFile(new URL(`${entry.name}/_sidebar.md`, root), 'utf8').catch(() => null);
    if (!sidebar) {
      continue;
    }
    assert.doesNotMatch(sidebar, /\]\((\.\/)?README\.md\)/, `${entry.name}/_sidebar.md links to README.md`);
  }
});

