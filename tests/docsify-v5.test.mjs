test('renders Mermaid and LikeC4 tokens with the Docsify v5 API', () => {
  const { renderCode } = loadCodeRenderer();
  const context = {
    origin: {
      code: token => `fallback:${token.text}`,
    },
  };

  // Mermaid source is emitted escaped and rendered later, from a placeholder.
  assert.equal(
    renderCode.call(context, { text: 'flowchart LR; A-->B', lang: 'mermaid' }),
    '<div class="mermaid-diagram"><div class="diagram-actions">' +
      '<button type="button" class="diagram-expand diagram-source" aria-expanded="false">&lt;/&gt; Source</button>' +
      '<button type="button" class="diagram-expand" aria-label="Open diagram in larger view"><span class="diagram-expand__icon" aria-hidden="true">&#10530;</span>Expand</button>' +
      '</div><pre class="mermaid">flowchart LR; A--&gt;B</pre>' +
      '<pre class="mermaid-source" data-lang="mermaid" hidden><code class="lang-mermaid">flowchart LR; A--&gt;B</code></pre></div>',
  );
  assert.equal(
    renderCode.call(context, {
      text: '// view: overview\nview overview {}',
      lang: 'likec4',
    }),
    '<likec4-view class="likec4-embed" view-id="overview" dynamic-variant="sequence"></likec4-view>',
  );
  assert.equal(
    renderCode.call(context, { text: 'const answer = 42;', lang: 'js' }),
    'fallback:const answer = 42;',
  );
});

